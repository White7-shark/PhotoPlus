// Writes the app's Android string resources from src/i18n:
//   strings/en.json        -> res/values/strings.xml (the default, English)
//   strings/<tag>.json     -> res/values-<qualifier>/strings.xml (hand translations)
//   every key              -> java/com/photoplus/i18n/StringTable.kt (key -> R.string id)
//
// English is the source: every key the app shows is in values/strings.xml,
// so Google Play's app-string translation (Play Console > Grow users >
// Translations > App strings) can translate all of it. The hand
// translations cover the most-seen words; any key a language lacks falls
// back to English until Play (or a person) translates it.
//
// Placeholders such as {days} are wrapped in <xliff:g> so translators keep
// them as they are. Run from the repo root after changing a string:
//   node tools/i18n/build-strings.mjs           (write)
//   node tools/i18n/build-strings.mjs --check   (fail when out of date)
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

const root = process.cwd();
const src = join(root, 'src/i18n');
const res = join(root, 'android/app/src/main/res');
const kt = join(root, 'android/app/src/main/java/com/photoplus/i18n/StringTable.kt');

const read = f => JSON.parse(readFileSync(f, 'utf8'));
const languages = read(join(src, 'languages.json'));
const en = read(join(src, 'strings/en.json'));

const KEY = /^[a-z][a-z0-9_]*$/;
const placeholders = s => [...s.matchAll(/\{(\w+)\}/g)].map(m => m[1]).sort();

const problems = [];
for (const k of Object.keys(en)) if (!KEY.test(k)) problems.push(`en: "${k}" is not a valid resource name`);

/** Android string-resource text: escaped, with placeholders marked as not to translate. */
function resourceText(s) {
  const esc = t =>
    t
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/\\/g, '\\\\')
      .replace(/'/g, "\\'")
      .replace(/"/g, '\\"')
      .replace(/\n/g, '\\n')
      .replace(/^([@?])/, '\\$1');
  return s
    .split(/(\{\w+\})/)
    .map(part => {
      const m = /^\{(\w+)\}$/.exec(part);
      return m ? `<xliff:g id="${m[1]}">{${m[1]}}</xliff:g>` : esc(part);
    })
    .join('');
}

function stringsXml(table, header, base) {
  // A literal % (as in "40% steadier") is text, not a format pattern.
  const lines = Object.entries(table).map(
    ([k, v]) => `    <string name="${k}"${v.includes('%') ? ' formatted="false"' : ''}>${resourceText(v)}</string>`,
  );
  const app = base ? '    <string name="app_name" translatable="false">Photo Plus</string>\n' : '';
  // The default file holds every key; the translations hold some of them
  // (Play's translation, or English, fills the rest), so a missing
  // translation is expected rather than a mistake.
  const ignore = base ? ' tools:ignore="MissingTranslation"' : '';
  const ns =
    (base ? ' xmlns:tools="http://schemas.android.com/tools"' : '') +
    (lines.some(l => l.includes('<xliff:g')) ? ' xmlns:xliff="urn:oasis:names:tc:xliff:document:1.2"' : '');
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- ${header}
     Generated by tools/i18n/build-strings.mjs from src/i18n: edit the JSON there, not this file. -->
<resources${ns}${ignore}>
${app}${lines.join('\n')}
</resources>
`;
}

const outputs = new Map();
outputs.set(
  join(res, 'values/strings.xml'),
  stringsXml(en, 'English: the source of every translation (Google Play translates from this file).', true),
);

for (const lang of languages) {
  if (!lang.res) continue;
  const file = join(src, `strings/${lang.tag}.json`);
  if (!existsSync(file)) {
    problems.push(`${lang.tag}: no strings/${lang.tag}.json`);
    continue;
  }
  const table = read(file);
  const ordered = {};
  for (const k of Object.keys(en)) {
    if (!(k in table)) continue;
    const want = placeholders(en[k]).join(',');
    const got = placeholders(table[k]).join(',');
    if (want !== got) problems.push(`${lang.tag}: "${k}" has {${got}} but English has {${want}}`);
    if (!table[k].trim()) problems.push(`${lang.tag}: "${k}" is empty`);
    ordered[k] = table[k];
  }
  for (const k of Object.keys(table)) if (!(k in en)) problems.push(`${lang.tag}: "${k}" is not an English key`);
  outputs.set(
    join(res, `values-${lang.res}/strings.xml`),
    stringsXml(ordered, `${lang.english} (${lang.name}): translated by hand (${Object.keys(ordered).length} of ${Object.keys(en).length}).`, false),
  );
}

outputs.set(
  kt,
  `// Generated by tools/i18n/build-strings.mjs from src/i18n/strings/en.json. Do not edit.
package com.photoplus.i18n

import com.photoplus.R

/** Every string the app's screens read (its key in JS -> its resource). */
internal val STRING_TABLE: Map<String, Int> = mapOf(
${Object.keys(en)
  .map(k => `  "${k}" to R.string.${k},`)
  .join('\n')}
)
`,
);

if (problems.length) {
  console.error(problems.join('\n'));
  process.exit(1);
}

const check = process.argv.includes('--check');
let stale = 0;
for (const [path, text] of outputs) {
  const now = existsSync(path) ? readFileSync(path, 'utf8') : null;
  if (now === text) continue;
  if (check) {
    console.error(`out of date: ${path.slice(root.length + 1)}`);
    stale++;
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, text);
    console.log(`wrote ${path.slice(root.length + 1)}`);
  }
}
if (stale) {
  console.error('Run: node tools/i18n/build-strings.mjs');
  process.exit(1);
}
